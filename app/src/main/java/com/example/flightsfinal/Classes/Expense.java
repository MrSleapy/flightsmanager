package com.example.flightsfinal.Classes;

import androidx.room.Entity;
import androidx.room.ForeignKey;
import androidx.room.Ignore;
import androidx.room.Index;
import androidx.room.PrimaryKey;

// Defines this class as a Room table. Each expense belongs to one flight (1:N).
// Deleting a flight deletes all of its expenses (CASCADE).
@Entity(tableName = "expenses",
        foreignKeys = @ForeignKey(entity = Flight.class,
                parentColumns = "id",
                childColumns = "flightOwnerId",
                onDelete = ForeignKey.CASCADE),
        indices = {@Index("flightOwnerId")})
public class Expense {

    // --- DATABASE FIELDS ---

    // Auto-generates a unique ID for each new expense
    @PrimaryKey(autoGenerate = true)
    private long id;

    // The id of the flight this expense belongs to
    private long flightOwnerId;

    private ExpenseCategory category;
    private String description;

    // Amount in the original currency
    private double amount;

    // Currency code: ILS, EUR, USD
    private String currency;

    // Amount after conversion to shekels
    private double amountInShekels;

    // --- CONSTRUCTORS ---

    // Empty constructor required by Room
    public Expense() {
    }

    // The main constructor used to create new Expense objects (id is generated by Room)
    @Ignore
    public Expense(long flightOwnerId, ExpenseCategory category, String description,
                   double amount, String currency, double amountInShekels) {
        this.flightOwnerId = flightOwnerId;
        this.category = category;
        this.description = description;
        this.amount = amount;
        this.currency = currency;
        this.amountInShekels = amountInShekels;
    }

    // --- GETTERS AND SETTERS ---

    public long getId() { return id; }
    public void setId(long id) { this.id = id; }

    public long getFlightOwnerId() { return flightOwnerId; }
    public void setFlightOwnerId(long flightOwnerId) { this.flightOwnerId = flightOwnerId; }

    public ExpenseCategory getCategory() { return category; }
    public void setCategory(ExpenseCategory category) { this.category = category; }

    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }

    public double getAmount() { return amount; }
    public void setAmount(double amount) { this.amount = amount; }

    public String getCurrency() { return currency; }
    public void setCurrency(String currency) { this.currency = currency; }

    public double getAmountInShekels() { return amountInShekels; }
    public void setAmountInShekels(double amountInShekels) { this.amountInShekels = amountInShekels; }
}
